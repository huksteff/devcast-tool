import { _electron as electron, expect } from '@playwright/test';
import { spawn, execFileSync } from 'node:child_process';
import path from 'node:path';
import fs from 'node:fs';

const root = process.cwd();
const out = path.join(root, '.tmp', 'timeline-check');
fs.mkdirSync(out, { recursive: true });
const media = path.join(out, 'sample.mp4');
execFileSync(path.join(root, 'node_modules/ffmpeg-static/ffmpeg.exe'), ['-y', '-f', 'lavfi', '-i', 'testsrc2=size=640x360:rate=25', '-t', '6', '-c:v', 'libx264', media], { stdio: 'ignore' });
const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', 'preview', '--host', '127.0.0.1', '--port', '5189', '--strictPort'], { cwd: root, stdio: 'ignore', windowsHide: true });
let app;
const errors = [];
try {
  await expect.poll(async () => { try { return (await fetch('http://127.0.0.1:5189')).status; } catch { return 0; } }).toBe(200);
  const packaged = process.argv.includes('--packaged');
  app = await electron.launch({ executablePath: path.join(root, packaged ? (process.env.DEVCAST_TEST_EXE || 'release/win-unpacked/DevCast.exe') : 'node_modules/electron/dist/electron.exe'), args: packaged ? [] : ['.'], env: { ...process.env, VITE_DEV_SERVER_URL: 'http://127.0.0.1:5189', DEVCAST_DEV_OPEN_RECORDING_INPUT: media }, timeout: 30000 });
  app.on('window', page => page.on('pageerror', error => errors.push(error.message)));
  await expect.poll(() => app.windows().find(p => p.url().includes('windowType=editor'))?.url(), { timeout: 30000 }).toBeTruthy();
  const editor = app.windows().find(p => p.url().includes('windowType=editor'));
  await editor.getByRole('button', { name: 'Open Timeline Window' }).waitFor({ timeout: 30000 });
  const panel = editor.locator('[data-timeline-panel]');
  const originalHeight = await panel.evaluate(e => e.getBoundingClientRect().height);
  const grip = await editor.getByRole('separator', { name: 'Resize timeline' }).boundingBox();
  await editor.mouse.move(grip.x + grip.width / 2, grip.y + 3);
  await editor.mouse.down();
  await editor.mouse.move(grip.x + grip.width / 2, grip.y - 120, { steps: 10 });
  await editor.mouse.up();
  expect(await panel.evaluate(e => e.getBoundingClientRect().height)).toBeGreaterThan(originalHeight + 80);
  const enlarged = await panel.evaluate(e => e.getBoundingClientRect().height);
  const newGrip = await editor.getByRole('separator', { name: 'Resize timeline' }).boundingBox();
  await editor.mouse.move(newGrip.x + newGrip.width / 2, newGrip.y + 3);
  await editor.mouse.down();
  await editor.mouse.move(newGrip.x + newGrip.width / 2, newGrip.y + 60, { steps: 5 });
  await editor.mouse.up();
  await expect.poll(() => panel.evaluate(e => e.getBoundingClientRect().height)).toBeLessThan(enlarged - 30);
  const row = editor.locator('[data-timeline-row]').first();
  const originalRowHeight = await row.evaluate(e => e.getBoundingClientRect().height);
  await editor.getByTestId('timeline-scroll').hover();
  await editor.keyboard.down('Shift');
  await editor.mouse.wheel(0, -120);
  await editor.keyboard.up('Shift');
  await expect.poll(() => row.evaluate(e => e.getBoundingClientRect().height)).toBeGreaterThan(originalRowHeight);
  const source = await editor.evaluate(() => window.electronAPI.getSelectedSource());
  const primary = await app.evaluate(({ screen }) => String(screen.getPrimaryDisplay().id));
  expect(source.sourceType).toBe('screen');
  expect(source.display_id).toBe(primary);
  await editor.getByRole('button', { name: 'Open Timeline Window' }).click();
  await expect.poll(() => app.windows().find(p => p.url().includes('windowType=timeline-window'))?.url()).toBeTruthy();
  const child = app.windows().find(p => p.url().includes('windowType=timeline-window'));
  await child.getByTestId('timeline-scroll').waitFor({ timeout: 15000 });
  // Packaged child windows load from file, while the editor uses the local server.
  await app.evaluate(async ({ BrowserWindow, app }) => {
    const child = BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('windowType=timeline-window'));
    await child.loadFile(app.getAppPath() + '/dist/index.html', { query: { windowType: 'timeline-window' } });
  });
  await child.getByTestId('timeline-scroll').waitFor({ timeout: 15000 });
  expect(await child.getByTestId('timeline-scroll').evaluate(e => e.getBoundingClientRect().height)).toBeGreaterThan(100);
  await expect(editor.getByTestId('timeline-scroll')).toBeHidden();
  const childRow = child.locator('[data-timeline-row]').first();
  const beforeShrink = await childRow.evaluate(e => e.getBoundingClientRect().height);
  await child.getByTestId('timeline-scroll').hover();
  await child.keyboard.down('Shift');
  await child.mouse.wheel(0, 120);
  await child.keyboard.up('Shift');
  await expect.poll(() => childRow.evaluate(e => e.getBoundingClientRect().height)).toBeLessThan(beforeShrink);
  await child.getByRole('button', { name: 'Play', exact: true }).click();
  await expect(child.getByRole('button', { name: 'Pause', exact: true })).toBeVisible();
  await expect.poll(() => editor.evaluate(() => document.querySelector('video')?.paused)).toBe(false);
  await child.getByRole('button', { name: 'Pause', exact: true }).click();
  await expect.poll(() => editor.evaluate(() => document.querySelector('video')?.paused)).toBe(true);
  await child.getByRole('button', { name: 'Skip forward', exact: true }).click();
  await expect.poll(() => editor.evaluate(() => document.querySelector('video')?.currentTime)).toBeGreaterThan(1);
  await child.evaluate(() => window.electronAPI.sendTimelineWindowMessage({ type: 'action', action: { type: 'seek', time: 2 } }));
  await expect.poll(() => editor.evaluate(() => document.querySelector('video')?.currentTime), { timeout: 10000 }).toBeGreaterThan(1.8);
  await child.evaluate(() => window.electronAPI.sendTimelineWindowMessage({ type: 'action', action: { type: 'zoom-added', span: { start: 1000, end: 3000 } } }));
  await expect.poll(() => child.locator('[data-timeline-item]').count()).toBeGreaterThan(1);
  await expect.poll(() => child.locator('[data-testid="clip-filmstrip"] img').count(), { timeout: 20000 }).toBeGreaterThan(0);
  await child.screenshot({ path: path.join(out, 'detached.png') });
  await child.getByRole('button', { name: 'Close window' }).click();
  await expect(editor.getByTestId('timeline-scroll')).toBeVisible();
  expect(errors).toEqual([]);
  console.log('PASS: panel resize; Shift+wheel rows; Play/Pause/Skip; primary monitor; detached render; dock hidden; seek; edit; redock; no renderer errors');
} finally {
  console.log('Renderer errors:', errors);
  await app?.close();
  server.kill();
}
